    /// serde_json parses `/open` strictly: a bare `\` turns `C:\Users` into a 400 and
    /// `C:\new` into a newline. Every value is escaped `\` -> `\\`, and the body reaches
    /// curl.exe through a file, so MSVCRT argv parsing never sees a trailing `\` + quote.
    #[test]
    fn cmd_shim_escapes_backslashes_and_sends_the_body_from_a_file() {
        let s = shim_cmd();
        for v in ["path_abs", "sname", "prompt_abs"] {
            let doubled = format!("!{v}:\\=\\\\!");
            assert!(s.contains(&doubled), "{v} backslashes not doubled");
        }
        assert!(
            s.contains("--data-binary \"@!bodyfile!\""),
            "body not sent from a file"
        );
        assert!(
            !s.contains("--data \"!body!\""),
            "body must not go through argv"
        );
        assert!(
            s.contains("rd /s /q \"!bodydir!\""),
            "temp body file not deleted"
        );
        // Two shims started in the same second draw the same %RANDOM%; the body's directory
        // must be claimed (mkdir fails on a taken name) rather than assumed unique.
        assert!(
            s.contains("mkdir \"!bodydir!\" 2>NUL || goto claim"),
            "temp body path not claimed atomically"
        );
    }

    /// `curl -f` folds a 400 into the same failure as "nothing listening", which sent a
    /// refusal down the cold-start path. Both shims read the status instead.
    #[test]
    fn shims_branch_on_the_http_status_not_curls_exit_code() {
        for s in [shim_sh(), shim_cmd()] {
            assert!(s.contains("%{http_code}"), "status not captured");
            assert!(!s.contains("curl -sf") && !s.contains("curl.exe -sf"));
            assert!(s.contains("Conduit rejected the request"), "400 message");
            assert!(s.contains("refused the CLI token"), "403 message");
            assert!(s.contains("invalid --worktree slug"), "slug check");
        }
        // Only "nothing answered" may cold start.
        let sh = shim_sh();
        assert!(sh.contains("000) return 1 ;;"));
        assert!(sh.trim_end().ends_with("answered || cold_start"));
    }

