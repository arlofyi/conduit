    #[test]
    fn a_v1_shim_reads_as_installed_but_outdated_and_can_be_replaced_or_removed() {
        let dir = tmp();
        let file = dir.join(shim_file_name());
        let v1 = "#!/bin/sh\n# conduit-cli-shim-v1\nexit 9\n";

        fs::write(&file, v1).unwrap();
        let s = status_in(&dir);
        assert!(s.installed && s.outdated, "{s:?}");

        install_in(&dir).unwrap();
        let s = status_in(&dir);
        assert!(s.installed && !s.outdated, "{s:?}");

        fs::write(&file, v1).unwrap();
        remove_in(&dir).unwrap();
        assert!(!file.exists());

        fs::write(&file, "#!/bin/sh\necho someone elses conduit\n").unwrap();
        assert!(install_in(&dir).is_err());
        assert!(remove_in(&dir).is_err());
        assert!(file.exists());
        fs::remove_dir_all(&dir).ok();
    }

